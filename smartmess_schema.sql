CREATE TABLE IF NOT EXISTS app_settings (
 id TINYINT PRIMARY KEY, value_json LONGTEXT NOT NULL, updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE IF NOT EXISTS hostels (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, name VARCHAR(120) NOT NULL UNIQUE,
 contact VARCHAR(200) NOT NULL DEFAULT '', description TEXT NULL, active TINYINT NOT NULL DEFAULT 1,
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE IF NOT EXISTS attendance_sessions (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, meal VARCHAR(20) NOT NULL, session_date DATE NOT NULL,
 start_time VARCHAR(5) NOT NULL, end_time VARCHAR(5) NOT NULL, hostel VARCHAR(120) NOT NULL DEFAULT '*',
 active TINYINT NOT NULL DEFAULT 1, custom TINYINT NOT NULL DEFAULT 0, timezone VARCHAR(80) NOT NULL,
 UNIQUE KEY uq_session_date_meal_hostel(session_date,meal,hostel)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE IF NOT EXISTS scanner_devices (
 user_id BIGINT UNSIGNED PRIMARY KEY, mode VARCHAR(20) NOT NULL, last_seen DATETIME NOT NULL,
 FOREIGN KEY(user_id) REFERENCES users(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE IF NOT EXISTS scan_events (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, user_id BIGINT UNSIGNED NOT NULL,
 student_id BIGINT UNSIGNED NULL, outcome VARCHAR(40) NOT NULL, created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 KEY idx_scan_events_date(created_at), FOREIGN KEY(user_id) REFERENCES users(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE IF NOT EXISTS notifications (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, user_id BIGINT UNSIGNED NULL, hostel VARCHAR(120) NULL,
 title VARCHAR(150) NOT NULL, body TEXT NOT NULL, kind VARCHAR(40) NOT NULL DEFAULT 'system',
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP, KEY idx_notifications_user(user_id,created_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE IF NOT EXISTS notification_reads (
 notification_id BIGINT UNSIGNED NOT NULL, user_id BIGINT UNSIGNED NOT NULL, read_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 PRIMARY KEY(notification_id,user_id), FOREIGN KEY(notification_id) REFERENCES notifications(id),
 FOREIGN KEY(user_id) REFERENCES users(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE IF NOT EXISTS rate_limits (
 bucket_key CHAR(64) PRIMARY KEY, hits INT NOT NULL, expires_at DATETIME NOT NULL, KEY idx_rate_expiry(expires_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE IF NOT EXISTS revoked_sessions (
 token_hash CHAR(64) PRIMARY KEY,
 user_id BIGINT UNSIGNED NOT NULL,
 expires_at DATETIME NOT NULL,
 revoked_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 KEY idx_revoked_session_expiry(expires_at),
 FOREIGN KEY(user_id) REFERENCES users(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
